export function levelOf(score, total) {
  const pct = total ? score / total : 0;
  if (pct >= 0.9) return 'מומחה/ית סגירות';
  if (pct >= 0.6) return 'בקיא/ה במדיניות';
  return 'בדרך ללמידה';
}
