// Normalize Hebrew for search: drop niqqud, geresh/gershayim variants and extra spaces.
export const normalize = (s) => String(s || '')
  .replace(/[֑-ׇ]/g, '')
  .replace(/[׳']/g, "'")
  .replace(/[״"]/g, '"')
  .replace(/\s+/g, ' ')
  .trim()
  .toLowerCase();

// Every word of the query must appear in the clause (label, text or id).
export function searchClauses(query) {
  const words = normalize(query).split(' ').filter(Boolean);
  if (!words.length) return [];
  return ALL_CLAUSES.filter(c => {
    const hay = normalize(`${c.id} ${c.label} ${c.text} ${c.chapterTitle}`);
    return words.every(w => hay.includes(w));
  });
}

export const escapeRegExp = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

